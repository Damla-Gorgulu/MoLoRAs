def encode_prompt_sdxl(
    pipeline: StableDiffusionXLPipeline,
    prompt: str,
    device: torch.device,
    do_classifier_free_guidance: bool = True,
) -> tuple[torch.Tensor, torch.Tensor]:
    """
    Returns (prompt_embeds, pooled_prompt_embeds).
    If do_classifier_free_guidance: [2, S, 2048] and [2, 1280] (uncond then cond).
    Else: [1, S, 2048] and [1, 1280].
    """
    prompt_embeds, neg_embeds, pooled, neg_pooled = pipeline.encode_prompt(
        prompt=prompt,
        device=device,
        num_images_per_prompt=1,
        do_classifier_free_guidance=do_classifier_free_guidance,
        negative_prompt="" if do_classifier_free_guidance else None,
    )
    if do_classifier_free_guidance:
        # Concat [uncond, cond] for UNet (first half uncond, second cond)
        prompt_embeds = torch.cat([neg_embeds, prompt_embeds], dim=0)
        pooled = torch.cat([neg_pooled, pooled], dim=0)
    return prompt_embeds, pooled


def make_time_ids(
    device: torch.device,
    dtype: torch.dtype,
    height: int = 512,
    width: int = 512,
) -> torch.Tensor:
    ids = [height, width, 0, 0, height, width]
    return torch.tensor([ids], dtype=dtype, device=device)


def sdxl_latent_from_steps(
    unet,
    scheduler,
    latent: torch.Tensor,
    prompt_embeds: torch.Tensor,
    pooled_embeds: torch.Tensor,
    time_ids: torch.Tensor,
    num_inference_steps: int,
    lora_dict: Optional[dict[str, torch.Tensor]] = None,
    lora_scale: float = 1.0,
    guidance_scale: float = 7.5,
    fixed_timestep: Optional[torch.Tensor] = None,
    no_grad: bool = False,
) -> torch.Tensor:
    """
    Unified sampler for CLIP loss. Uses scale_model_input and optional CFG to match
    the SDXL pipeline so that even GT LoRA produces correct-looking images.
    """
    use_cfg = guidance_scale > 1.0 and prompt_embeds.shape[0] == 2
    if use_cfg:
        # time_ids must be [2, 6] for CFG
        if time_ids.shape[0] == 1:
            time_ids = time_ids.repeat(2, 1)
        added_cond = {"text_embeds": pooled_embeds, "time_ids": time_ids}
    else:
        added_cond = {"text_embeds": pooled_embeds, "time_ids": time_ids}

    def _merge_cfg(noise_pred: torch.Tensor) -> torch.Tensor:
        if not use_cfg:
            return noise_pred
        uncond, cond = noise_pred.chunk(2, dim=0)
        return uncond + guidance_scale * (cond - uncond)

    def _forward():
        if num_inference_steps == 1:
            if fixed_timestep is not None:
                t = fixed_timestep
            else:
                t = torch.randint(200, 800, (1,), device=latent.device)

            latent_in = latent
            if use_cfg:
                latent_in = torch.cat([latent_in, latent_in], dim=0)
            latent_in = scheduler.scale_model_input(latent_in, t)

            cm = apply_lora_hooks(unet, lora_dict, lora_scale) if lora_dict else _null_cm()
            with cm:
                noise_pred = unet(
                    sample=latent_in,
                    timestep=t,
                    encoder_hidden_states=prompt_embeds,
                    added_cond_kwargs=added_cond,
                ).sample
            noise_pred = _merge_cfg(noise_pred)

            alpha_bar = scheduler.alphas_cumprod[t.long().cpu()].to(latent.device, latent.dtype)
            x0 = (latent - (1 - alpha_bar).sqrt() * noise_pred) / alpha_bar.sqrt()
            return x0.clamp(-1, 1)

        scheduler.set_timesteps(num_inference_steps, device=latent.device)
        latents = latent * scheduler.init_noise_sigma

        for t in scheduler.timesteps:
            latent_in = torch.cat([latents, latents], dim=0) if use_cfg else latents
            latent_in = scheduler.scale_model_input(latent_in, t)

            cm = apply_lora_hooks(unet, lora_dict, lora_scale) if lora_dict else _null_cm()
            with cm:
                noise_pred = unet(
                    sample=latent_in,
                    timestep=t,
                    encoder_hidden_states=prompt_embeds,
                    added_cond_kwargs=added_cond,
                ).sample
            noise_pred = _merge_cfg(noise_pred)
            step_out = scheduler.step(noise_pred, t, latents)
            latents = step_out.prev_sample

        return latents

    if no_grad:
        with torch.no_grad():
            return _forward()
    return _forward()


@contextmanager
def _null_cm():
    yield


def _check_nan_inf(tensor: torch.Tensor, name: str, epoch: int, batch_idx: int, sample_i: int) -> bool:
    """Return True if tensor has nan/inf; print one-line debug and stats (min/max/mean)."""
    if not torch.isfinite(tensor).all():
        stats = f"min={tensor.min().item():.6f} max={tensor.max().item():.6f} mean={tensor.float().mean().item():.6f}"
        n_nan = torch.isnan(tensor).sum().item()
        n_inf = torch.isinf(tensor).sum().item()
        print(f"[DEBUG NaN] epoch={epoch} batch_idx={batch_idx} sample_i={sample_i} | {name} | nan_count={n_nan} inf_count={n_inf} | {stats}")
        return True
    return False


