def lora_key_to_module_path(key: str) -> str:
    """
    'unet.up_blocks.0.attentions.1...to_q.lora.down.weight'
    → 'up_blocks.0.attentions.1...to_q'
    """
    path = key.removeprefix("unet.")
    for suffix in (".lora.down.weight", ".lora.up.weight"):
        if path.endswith(suffix):
            return path[: -len(suffix)]
    raise ValueError(f"Unrecognised LoRA key format: {key!r}")


def build_module_map(keys: list[str]) -> dict[str, tuple[str, str]]:
    """
    Returns {module_path: (down_key, up_key)} for each LoRA-patched Linear.
    """
    modules: dict[str, dict[str, str]] = {}
    for k in keys:
        path = lora_key_to_module_path(k)
        modules.setdefault(path, {})
        if k.endswith(".lora.down.weight"):
            modules[path]["down"] = k
        else:
            modules[path]["up"] = k
    return {p: (v["down"], v["up"]) for p, v in modules.items()}


@contextmanager
def apply_lora_hooks(
    unet,
    lora_dict: dict[str, torch.Tensor],
    scale: float = 1.0,
):
    """
    Temporarily patches UNet Linear layers with LoRA deltas via forward hooks.
    Gradients flow back through the delta into lora_dict values.

    lora_dict values (per-sample, no batch dim):
        down key → [rank, in_features]
        up   key → [out_features, rank]
    """
    handles = []
    module_map = build_module_map(list(lora_dict.keys()))

    for module_path, (down_key, up_key) in module_map.items():
        try:
            linear = unet.get_submodule(module_path)
        except AttributeError:
            continue

        lora_A = lora_dict[down_key]   # [rank, in_features]
        lora_B = lora_dict[up_key]     # [out_features, rank]

        def _make_hook(A: torch.Tensor, B: torch.Tensor, s: float):
            def hook(module, inp, out):
                # Compute the LoRA delta in the same dtype as the UNet output
                # (usually fp16/bf16) to keep memory low and avoid dtype
                # mismatches in matmuls.
                compute_dtype = out.dtype

                x = inp[0].to(compute_dtype)      # [..., in_features]
                A_cast = A.to(compute_dtype)      # [rank, in_features]
                B_cast = B.to(compute_dtype)      # [out_features, rank]

                delta = (x @ A_cast.t()) @ B_cast.t() * s   # [..., out_features]
                return out + delta
            return hook

        h = linear.register_forward_hook(_make_hook(lora_A, lora_B, scale))
        handles.append(h)

    try:
        yield
    finally:
        for h in handles:
            h.remove()


