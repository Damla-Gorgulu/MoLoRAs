# CLIP image encoding
# ═══════════════════════════════════════════════════════════════════════════════

def clip_encode_x0(
    vae: AutoencoderKL,
    clip: CLIPVisionModel,
    x0_latent: torch.Tensor,
    no_grad: bool = False,
) -> torch.Tensor:
    """
    VAE-decode a latent, normalise to [0,1], resize to 224, then CLIP-encode.

    x0_latent : [1, 4, H/8, W/8]
    returns   : [1, clip_hidden]  (pooler_output / CLS embedding)
    """
    def _compute():
        # Match latent dtype/device to the VAE to avoid dtype/device mismatches,
        # especially when the VAE is loaded in fp16.
        latent = x0_latent.to(dtype=vae.dtype, device=vae.device)
        decoded = vae.decode(latent / vae.config.scaling_factor).sample  # [1,3,H,W] in [-1,1]
        img_01 = (decoded.float().clamp(-1, 1) + 1) / 2
        img_224 = F.interpolate(img_01, size=(224, 224), mode="bilinear", align_corners=False)
        return clip(pixel_values=img_224).pooler_output  # [1, D]

    if no_grad:
        with torch.no_grad():
            return _compute()
    return _compute()


def save_latent_as_image(
    vae: AutoencoderKL,
    x0_latent: torch.Tensor,
    path: Path,
) -> None:
    """Decode a single x0 latent [1, 4, H, W] to [0,1] image and save to path."""
    with torch.no_grad():
        latent = x0_latent.to(dtype=vae.dtype, device=vae.device)
        decoded = vae.decode(latent / vae.config.scaling_factor).sample
        img_01 = (decoded.float().clamp(-1, 1) + 1) / 2
    # img_01: [1, 3, H, W], [0, 1]
    save_image(img_01.cpu(), str(path))


