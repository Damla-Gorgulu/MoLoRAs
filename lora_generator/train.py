# ═══════════════════════════════════════════════════════════════════════════════
# Main
# ═══════════════════════════════════════════════════════════════════════════════

def main() -> None:
    args = parse_args()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    os.makedirs(args.output_dir, exist_ok=True)

    if args.wandb:
        import wandb
        wandb.init(
            project=args.wandb_project,
            name=args.wandb_run_name,
            config=vars(args),
        )

    # ── Dataset ──────────────────────────────────────────────────────────────
    vae_hw = (
        (args.generation_height, args.generation_width)
        if args.style_encoder == "vae_latents"
        else None
    )
    dataset = StyleLoRADataset(
        checkpoint_dir=args.checkpoint_dir,
        image_dir=args.image_dir,
        clip_model_id=args.clip_model_id,
        cache_loras=True,
        vae_image_size=vae_hw,
    )
    print(f"Dataset: {len(dataset)} styles → {dataset.styles}")

    loader = DataLoader(
        dataset,
        batch_size=args.batch_size,
        shuffle=True,
        collate_fn=collate_fn,
        drop_last=False,
    )

    # ── LoRA Generator ───────────────────────────────────────────────────────
    sample = dataset[0]
    model = LoRAGenerator.from_sample_lora(
        sample_lora_dict=sample["lora_dict"],
        d_model=args.d_model,
        n_layers=args.n_layers,
        n_heads=args.n_heads,
        clip_model=args.clip_model_id,
        style_encoder=args.style_encoder,
        latent_patch_size=args.latent_patch_size,
    ).to(device)

    trainable_params = [p for p in model.parameters() if p.requires_grad]
    n_trainable = sum(p.numel() for p in trainable_params)
    print(f"LoRAGenerator trainable parameters: {n_trainable:,}")

    optimizer = torch.optim.AdamW(
        trainable_params, lr=args.lr, weight_decay=args.weight_decay
    )

    # ── SDXL + VAE + CLIP for image-space loss ───────────────────────────────
    sdxl_unet = None
    vae = None
    clip_for_loss = None
    scheduler = None
    prompt_embeds = None
    pooled_embeds = None
    time_ids = None
    latent_h = latent_w = None

    vae_override = args.pretrained_vae_model_name_or_path or args.vae_model_id
    need_vae = args.style_encoder == "vae_latents" or args.lambda_clip > 0
    if need_vae:
        print("Loading SDXL VAE (B-LoRA script convention: base subfolder or override) …")
        vae = load_sdxl_vae(
            args.sdxl_model_id,
            pretrained_vae_model_name_or_path=vae_override if vae_override else None,
            torch_dtype=torch.float32,
        ).to(device)
        vae.requires_grad_(False)

    if args.lambda_clip > 0:
        print("Loading SDXL for CLIP image loss …")
        if vae is None:
            raise RuntimeError("CLIP loss requires a VAE; this should not happen.")

        sdxl_pipe = StableDiffusionXLPipeline.from_pretrained(
            args.sdxl_model_id,
            vae=vae,
            torch_dtype=torch.float16,
        ).to(device)
        sdxl_unet = sdxl_pipe.unet
        sdxl_unet.requires_grad_(False)
        sdxl_pipe.text_encoder.requires_grad_(False)
        sdxl_pipe.text_encoder_2.requires_grad_(False)

        with torch.no_grad():
            prompt_embeds, pooled_embeds = encode_prompt_sdxl(
                sdxl_pipe,
                args.generation_prompt,
                device,
                do_classifier_free_guidance=(getattr(args, "guidance_scale", 7.5) > 1.0),
            )

        time_ids = make_time_ids(
            device, torch.float16,
            height=args.generation_height,
            width=args.generation_width,
        )

        # Use same scheduler as B-LoRA validation (DPMSolverMultistepScheduler) so
        # generation matches how B-LoRA checkpoints are meant to be used (see
        # train_dreambooth_b-lora_sdxl.py validation path).
        scheduler_config = sdxl_pipe.scheduler.config
        scheduler_args = {}
        variance_type = getattr(
            scheduler_config, "variance_type",
            scheduler_config.get("variance_type") if isinstance(scheduler_config, dict) else None,
        )
        if variance_type in ["learned", "learned_range"]:
            scheduler_args["variance_type"] = "fixed_small"
        scheduler = DPMSolverMultistepScheduler.from_config(
            scheduler_config, **scheduler_args
        )

        clip_for_loss = CLIPVisionModel.from_pretrained(args.clip_model_id).to(device)
        clip_for_loss.requires_grad_(False)

        latent_h = args.generation_height // 8
        latent_w = args.generation_width  // 8

        # Free pipeline object (keep unet, vae)
        del sdxl_pipe
        torch.cuda.empty_cache()

        if args.save_training_images:
            (Path(args.output_dir) / "training_samples").mkdir(parents=True, exist_ok=True)

    # ── Training loop ────────────────────────────────────────────────────────
    for epoch in range(1, args.epochs + 1):
        model.train()
        sum_loss_w = 0.0
        sum_loss_c = 0.0
        n_steps = 0
        use_clip = (
            args.lambda_clip > 0
            and sdxl_unet is not None
            and epoch > args.clip_loss_warmup_epochs
        )
        # Linear ramp: after warmup, scale lambda_clip from 0 to full over clip_ramp_epochs
        if use_clip:
            epochs_since_warmup = epoch - args.clip_loss_warmup_epochs
            ramp = min(1.0, epochs_since_warmup / args.clip_ramp_epochs)
            effective_lambda_clip = args.lambda_clip * ramp
        else:
            effective_lambda_clip = 0.0

        # Progress bar over training batches for this epoch
        batch_idx = 0
        for batch in tqdm(loader, desc=f"Epoch {epoch}/{args.epochs}", leave=False):
            pixel_values = batch["pixel_values"].to(device)
            lora_batch = {k: v.to(device) for k, v in batch["lora_dict"].items()}
            B = pixel_values.shape[0]

            optimizer.zero_grad()

            # ── Forward ────────────────────────────────────────────────
            if args.style_encoder == "vae_latents":
                if vae is None:
                    raise RuntimeError("style_encoder=vae_latents requires VAE loading.")
                vp = batch["vae_pixel_values"].to(device=device, dtype=vae.dtype)
                with torch.no_grad():
                    lat = encode_rgb_to_scaled_latents(vae, vp, sample=True)
                generated_lora = model(scaled_latents=lat.float())
            else:
                generated_lora = model(pixel_values=pixel_values)

            # ── Loss 1: weight MSE ─────────────────────────────────────
            loss_w = sum(
                F.mse_loss(generated_lora[k], lora_batch[k].float())
                for k in generated_lora
            ) / len(generated_lora)

            # ── Loss 2: CLIP image MSE ─────────────────────────────────
            loss_c = torch.zeros(1, device=device)

            if use_clip:
                per_sample_clip = []

                for i in range(B):
                    # Unbatch: per-sample LoRA dicts
                    gen_lora_i = {k: v[i] for k, v in generated_lora.items()}
                    gt_lora_i  = {k: v[i].float() for k, v in lora_batch.items()}

                    # Same starting noise for both (ensures comparable images)
                    z = torch.randn(
                        1, 4, latent_h, latent_w,
                        device=device, dtype=torch.float16,
                    )

                    half = {"dtype": torch.float16}

                    # Run num_inference_steps of DDIM for each path; then one backward
                    # of the cosine loss flows through the entire chain (all steps) to
                    # the generator — we do not backprop per-step, only once per sample.
                    fixed_t = (
                        torch.tensor([args.sdxl_timestep], device=device)
                        if args.sdxl_timestep is not None
                        else None
                    )

                    x0_gen = sdxl_latent_from_steps(
                        unet=sdxl_unet,
                        scheduler=scheduler,
                        latent=z,
                        prompt_embeds=prompt_embeds.to(**half),
                        pooled_embeds=pooled_embeds.to(**half),
                        time_ids=time_ids,
                        num_inference_steps=args.num_inference_steps,
                        lora_dict={k: v.to(**half) for k, v in gen_lora_i.items()},
                        lora_scale=args.lora_scale,
                        guidance_scale=args.guidance_scale,
                        fixed_timestep=fixed_t,
                        no_grad=False,
                    )
                    if _check_nan_inf(x0_gen.float(), "x0_gen", epoch, batch_idx, i):
                        continue  # skip this sample for loss to avoid backprop through nan

                    # GT path: load LoRA into UNet like B-LoRA inference (no hooks)
                    gt_lora_device = next(iter(gt_lora_i.values())).device
                    LoraLoaderMixin.load_lora_into_unet(
                        {k: v.to(**half) for k, v in gt_lora_i.items()},
                        None,
                        sdxl_unet,
                    )
                    try:
                        x0_gt = sdxl_latent_from_steps(
                            unet=sdxl_unet,
                            scheduler=scheduler,
                            latent=z,
                            prompt_embeds=prompt_embeds.to(**half),
                            pooled_embeds=pooled_embeds.to(**half),
                            time_ids=time_ids,
                            num_inference_steps=args.num_inference_steps,
                            lora_dict=None,
                            lora_scale=args.lora_scale,
                            guidance_scale=args.guidance_scale,
                            fixed_timestep=fixed_t,
                            no_grad=True,
                        )
                    finally:
                        # Clear loaded LoRA so next sample's gen path doesn't see GT LoRA
                        zero_lora = {
                            k: torch.zeros_like(v, device=gt_lora_device, dtype=v.dtype)
                            for k, v in gt_lora_i.items()
                        }
                        LoraLoaderMixin.load_lora_into_unet(zero_lora, None, sdxl_unet)

                    if _check_nan_inf(x0_gt.float(), "x0_gt", epoch, batch_idx, i):
                        continue

                    # Optionally save gen vs gt images (first sample of first batch, every N epochs)
                    if (
                        args.save_training_images
                        and (epoch % args.save_training_images_every == 0)
                        and batch_idx == 0
                        and i == 0
                    ):
                        save_dir = Path(args.output_dir) / "training_samples"
                        style_name = batch["style_names"][i]
                        save_latent_as_image(
                            vae, x0_gen.detach().float(), save_dir / f"epoch_{epoch:04d}_{style_name}_gen.png"
                        )
                        save_latent_as_image(
                            vae, x0_gt.float(), save_dir / f"epoch_{epoch:04d}_{style_name}_gt.png"
                        )

                    # CLIP embeddings — VAE decode + CLIP encode
                    # Gradients flow through generated path only
                    clip_gen = clip_encode_x0(vae, clip_for_loss, x0_gen.float(), no_grad=False)
                    if _check_nan_inf(clip_gen, "clip_gen", epoch, batch_idx, i):
                        continue

                    clip_gt  = clip_encode_x0(vae, clip_for_loss, x0_gt.float(),  no_grad=True)
                    if _check_nan_inf(clip_gt, "clip_gt", epoch, batch_idx, i):
                        continue

                    # Cosine similarity loss: 1 - cos(clip_gen, clip_gt)
                    gen_norm = F.normalize(clip_gen, p=2, dim=-1)
                    gt_norm  = F.normalize(clip_gt.detach(), p=2, dim=-1)
                    cos_sim  = (gen_norm * gt_norm).sum(dim=-1)  # [batch_dim]
                    sample_loss = 1.0 - cos_sim.mean()
                    if _check_nan_inf(sample_loss.unsqueeze(0), "cos_loss", epoch, batch_idx, i):
                        continue

                    per_sample_clip.append(sample_loss)

                if len(per_sample_clip) > 0:
                    loss_c = torch.stack(per_sample_clip).mean()
                # else: loss_c stays 0 (no valid CLIP samples this batch)

            # ── Optimise ───────────────────────────────────────────────
            total_loss = loss_w + effective_lambda_clip * loss_c
            if not torch.isfinite(total_loss).all():
                print(f"[DEBUG NaN] epoch={epoch} batch_idx={batch_idx} | total_loss nan/inf (loss_w={loss_w.item():.6f} loss_c={loss_c.item():.6f})")
            total_loss.backward()
            torch.nn.utils.clip_grad_norm_(trainable_params, max_norm=1.0)
            optimizer.step()

            sum_loss_w += loss_w.item()
            sum_loss_c += loss_c.item()
            n_steps += 1
            batch_idx += 1

        # ── Logging ────────────────────────────────────────────────────
        avg_w = sum_loss_w / n_steps
        avg_c = sum_loss_c / n_steps
        avg_total = avg_w + effective_lambda_clip * avg_c
        print(
            f"[{epoch:04d}/{args.epochs}]  "
            f"loss_weight={avg_w:.6f}  "
            f"loss_clip={avg_c:.6f}  "
            f"total={avg_total:.6f}"
        )

        if args.wandb:
            import wandb
            wandb.log({
                "epoch": epoch,
                "loss/weight_mse": avg_w,
                "loss/clip_image": avg_c,
                "loss/total": avg_total,
            })

        # ── Checkpoint ─────────────────────────────────────────────────
        if epoch % args.save_every == 0 or epoch == args.epochs:
            save_path = Path(args.output_dir) / f"checkpoint_epoch{epoch:04d}.pt"
            torch.save(
                {
                    "epoch": epoch,
                    "model_state_dict": model.state_dict(),
                    "optimizer_state_dict": optimizer.state_dict(),
                    "args": vars(args),
                    "keys": model.keys,
                    "key_shapes": model.key_shapes,
                },
                save_path,
            )
            print(f"  → Saved {save_path}")

    if args.wandb:
        import wandb
        wandb.finish()


if __name__ == "__main__":
    main()
